func renderLTMLPDF(t *testing.T, input string, assetFS fs.FS) string {
	t.Helper()

	var opts []ParseOption
	if assetFS != nil {
		opts = append(opts, WithAssetFS(assetFS))
	}
	doc, err := Parse([]byte(input), opts...)
	if err != nil {
		t.Fatal(err)
	}

	baseWriter := pdf.NewDocWriter()
	fonts, err := afm_fonts.Default()
	if err != nil {
		t.Fatal(err)
	}
	baseWriter.AddFontSource(fonts)
	if assetFS != nil {
		baseWriter.SetAssetFS(assetFS)
	}
	writer := &ltpdf.DocWriter{DocWriter: baseWriter}

	if err := doc.Print(writer); err != nil {
		t.Fatal(err)
	}

	var buf bytes.Buffer
	if _, err := baseWriter.WriteTo(&buf); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

func TestAccessibilityReplacementTextIsReservedForArabic(t *testing.T) {
	tests := []struct {
		name string
		text string
		want string
	}{
		{name: "latin", text: "Hello world"},
		{name: "chinese", text: "中文可逐字选择"},
		{name: "arabic", text: "مرحبا بالعالم", want: "مرحبا بالعالم"},
		{name: "mixed arabic", text: "Page مرحبا 1", want: "Page مرحبا 1"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := accessibilityReplacementText(tt.text); got != tt.want {
				t.Fatalf("accessibilityReplacementText(%q) = %q, want %q", tt.text, got, tt.want)
			}
		})
	}
	if got := accessibilityTextLanguage("مرحبا"); got != "ar" {
		t.Fatalf("Arabic accessibility language = %q, want ar", got)
	}
	if got := accessibilityTextLanguage("中文"); got != "" {
		t.Fatalf("Chinese accessibility language = %q, want empty", got)
	}
}

