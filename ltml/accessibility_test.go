func TestArabicProgramArtifactAccessibilityAndExtraction(t *testing.T) {
	pdfPath := filepath.Join("samples", "test_033_arabic_program.pdf")
	pdfData, err := os.ReadFile(pdfPath)
	if err != nil {
		t.Fatal(err)
	}
	pdfText := string(pdfData)
	for _, want := range []string{"/Lang (ar)", "/S /Table", "/S /TR", "/S /TH", "/S /TD"} {
		if !strings.Contains(pdfText, want) {
			t.Fatalf("Arabic artifact missing %q", want)
		}
	}
	if _, err := exec.LookPath("pdftotext"); err != nil {
		t.Skip("pdftotext is unavailable")
	}
	raw, err := exec.Command("pdftotext", pdfPath, "-").CombinedOutput()
	if err != nil {
		t.Fatalf("pdftotext: %v\n%s", err, raw)
	}
	logical := decodePopplerRTLText(string(raw))
	for _, want := range []string{
		"برنامج أمسيات الحي الثقافية",
		"مساء الثلاثاء الرابع عشر من أبريل",
		"community@citylibrary.example",
	} {
		if !strings.Contains(logical, want) {
			t.Fatalf("decoded extraction missing %q; raw=%q logical=%q", want, string(raw), logical)
		}
	}
}

// decodePopplerRTLText converts Poppler's plain-text transport convention
// (visual codepoint order inside an RLE/PDF pair) back to logical order. The
// controls are generated by Poppler and are not present in PDF ActualText.
func decodePopplerRTLText(text string) string {
	runes := []rune(text)
	out := make([]rune, 0, len(runes))
	for i := 0; i < len(runes); i++ {
		if runes[i] != '\u202B' {
			if runes[i] != '\u202C' && runes[i] != '\u202A' {
				out = append(out, runes[i])
			}
			continue
		}
		end := i + 1
		for end < len(runes) && runes[end] != '\u202C' {
			end++
		}
		for j := end - 1; j > i; j-- {
			if runes[j] != '\u202A' && runes[j] != '\u202C' {
				out = append(out, runes[j])
			}
		}
		i = end
	}
	return string(out)
}

func TestLTML_UAEnablesTaggedPDF(t *testing.T) {
	pdfText := renderLTMLPDF(t, `
<ltml ua="true">
  <page>
    <p>Hello <a uri="https://example.com">world</a></p>
  </page>
</ltml>`, nil)

	for _, fragment := range []string{
		"%PDF-1.7\n",
		"/StructTreeRoot",
		"/S /P",
		"/S /Link",
	} {
		if !strings.Contains(pdfText, fragment) {
			t.Fatalf("expected tagged fragment %q in output:\n%s", fragment, pdfText)
		}
	}
	if strings.Contains(pdfText, "/ActualText (Hello world)") {
		t.Fatalf("text structure should rely on rendered text and ToUnicode:\n%s", pdfText)
	}
}

